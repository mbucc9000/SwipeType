#!/usr/bin/env python3
# Generates STLexiconData.c (the SwipeType word list, compiled into the tweak) from wordfreq.
#
#   pip install wordfreq
#   python tools/make_lexicon.py [count]        (default 50000; run from the project folder)
#
# Words come from wordfreq's English "large" list (Robyn Speer, data CC BY-SA 4.0), most
# frequent first, with score = round(zipf * 100). Kept: plain a-z words of 2+ letters, real
# contractions (don't, I'm, you're, would've...), and common possessives. Apostrophe-less
# spellings of contractions ("dont", "im") are folded into the contraction, except where the
# plain spelling is a real word of its own ("its", "were", "well", "cant", "ill"...).

import math
import re
import sys

from wordfreq import top_n_list, zipf_frequency

COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 50000
OUT = "STLexiconData.c"

WORD = re.compile(r"^[a-z]+(?:'[a-z]+)?$")
NT_BASES = {"do", "does", "did", "is", "are", "was", "were", "has", "have", "had", "wo", "ca",
            "could", "would", "should", "must", "might", "need", "ai", "dare"}
PRON = {"i", "you", "he", "she", "it", "we", "they", "that", "there", "who", "what", "where",
        "when", "why", "how", "this", "here", "would", "could", "should", "might", "must"}
S_ALWAYS = {"it", "that", "he", "she", "what", "there", "here", "who", "let", "where", "how",
            "when", "why", "everyone", "everybody", "nobody", "somebody", "someone",
            "something", "nothing", "everything", "today", "one"}
APOS_WHITELIST = {"y'all", "ma'am", "o'clock"}
POSSESSIVE_MIN_ZIPF = 3.3
REAL_COLLIDERS = {"its", "were", "well", "ill", "wont", "cant", "shell", "hell", "id", "wed",
                  "shed", "lets", "wee", "ones", "nothings", "somethings"}
DROP = {"de", "la", "le", "el", "en", "et", "al", "du", "der", "die", "das", "und", "von",
        "les", "des", "il", "di", "da", "na", "ii", "iii", "iv", "vi", "vii", "viii", "xi",
        "www", "http", "https", "com", "org", "html", "php", "jpg", "png", "pdf", "rt"}


def keep_apostrophe(w):
    if w in APOS_WHITELIST:
        return True
    base, suf = w.split("'")
    if suf == "t":
        return base.endswith("n") and base[:-1] in NT_BASES
    if suf in ("d", "ll", "ve", "re", "m"):
        return base in PRON and not (suf == "m" and base != "i")
    if suf == "s":
        return len(base) >= 2 and (base in S_ALWAYS or zipf_frequency(w, "en") >= POSSESSIVE_MIN_ZIPF)
    return False


def build(count):
    entries, order = {}, []
    for w in top_n_list("en", 400000, wordlist="large"):
        if not WORD.match(w) or len(w) < 2 or w in DROP:
            continue
        if "'" in w and not keep_apostrophe(w):
            continue
        entries[w] = zipf_frequency(w, "en")
        order.append(w)

    merge_target = {}
    for w in order:
        if "'" not in w or w in APOS_WHITELIST:
            continue
        base, suf = w.split("'")
        if suf == "s" and base not in S_ALWAYS:
            continue
        plain = w.replace("'", "")
        if plain in REAL_COLLIDERS:
            continue
        if plain not in merge_target or entries[w] > entries[merge_target[plain]]:
            merge_target[plain] = w
    for plain, target in merge_target.items():
        if plain in entries:
            entries[target] = math.log10(10 ** entries[target] + 10 ** entries[plain])
            del entries[plain]

    words = sorted(entries, key=lambda w: -entries[w])[:count]
    return [(w, int(round(entries[w] * 100))) for w in words]


def main():
    lex = build(COUNT)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/make_lexicon.py - do not edit.\n")
        f.write("// Word list derived from wordfreq (Robyn Speer), data licensed CC BY-SA 4.0:\n")
        f.write("// https://github.com/rspeer/wordfreq - https://creativecommons.org/licenses/by-sa/4.0/\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("const int STLexiconDataCount = %d;\n\n" % len(lex))
        f.write("// NUL-separated words, most frequent first.\n")
        f.write("const char STLexiconDataWords[] =\n")
        for i in range(0, len(lex), 8):
            chunk = lex[i:i + 8]
            f.write("    " + " ".join('"%s\\0"' % w for w, _ in chunk) + "\n")
        f.write("    ;\n\n")
        f.write("// round(zipf * 100) for each word above.\n")
        f.write("const uint16_t STLexiconDataScores[] = {\n")
        for i in range(0, len(lex), 16):
            f.write("    " + ", ".join(str(s) for _, s in lex[i:i + 16]) + ",\n")
        f.write("};\n")
    print("wrote %s: %d words, last zipf %.2f" % (OUT, len(lex), lex[-1][1] / 100.0))


if __name__ == "__main__":
    main()
